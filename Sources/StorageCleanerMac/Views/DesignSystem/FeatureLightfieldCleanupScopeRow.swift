import SwiftUI

/// D77: same set-A glass material as the main module art. Scope identity,
/// selection and scan policy still come from SafeCleanupScanScope / ScanStore.
struct FeatureLightfieldCleanupScopeRow: View {
    @Environment(\.colorScheme) private var scheme
    let scope: SafeCleanupScanScope
    let selected: Bool
    let onToggle: () -> Void
    var iconLibrary = LightfieldOptionIcon.library
    static let iconSide: CGFloat = 40
    static func resourceStem(_ scope: SafeCleanupScanScope) -> String {
        switch scope {
        case .caches: "scope-cleanup-cache"
        case .logs: "scope-cleanup-logs"
        case .temporaryFiles: "scope-cleanup-temporary"
        case .downloadResidue: "scope-cleanup-downloads"
        }
    }
    static func icon(_ scope: SafeCleanupScanScope) -> LightfieldOptionIcon {
        switch scope {
        case .caches: .cleanupSystemCache
        case .logs: .cleanupLogs
        case .temporaryFiles: .cleanupTemporaryFiles
        case .downloadResidue: .cleanupDownloadRemnants
        }
    }
    static func title(_ scope: SafeCleanupScanScope) -> String {
        switch scope {
        case .caches: L10n.text("系统缓存", "System Caches")
        case .logs: L10n.text("日志文件", "Log Files")
        case .temporaryFiles: L10n.text("临时文件", "Temporary Files")
        case .downloadResidue: L10n.text("下载残留", "Download Residue")
        }
    }
    static func detail(_ scope: SafeCleanupScanScope) -> String {
        switch scope {
        case .caches: L10n.text("应用与系统可重建的缓存", "Rebuildable app and system caches")
        case .logs: L10n.text("应用与系统生成的日志记录", "Logs generated by apps and the system")
        case .temporaryFiles: L10n.text("运行与安装过程留下的临时文件", "Temporary files from app use and installation")
        case .downloadResidue: L10n.text("下载留下的残余项，清理前逐项确认", "Download remnants; review each item before cleanup")
        }
    }
    var body: some View {
        let palette = FeatureLightfieldPalette.resolve(scheme)
        let probe = "lightfield.cleanup.scope." + Self.resourceStem(scope)
        Button(action: onToggle) {
            HStack(spacing: 14) {
                FeatureLightfieldCheck(selected: selected, module: .green)
                    .lightfieldComponentProbe(probe + ".check")
                LightfieldOptionIconView(icon: Self.icon(scope), library: iconLibrary, pointSize: Self.iconSide,
                    resourceNameOverride: Self.resourceStem(scope) + "-192")
                    .lightfieldComponentProbe(probe + ".icon")
                VStack(alignment: .leading, spacing: 4) {
                    Text(Self.title(scope)).font(.system(size: 16)).foregroundStyle(palette.fg)
                        .lineLimit(1).lightfieldComponentProbe(probe + ".title")
                    Text(Self.detail(scope)).font(.system(size: 12)).foregroundStyle(palette.fg3)
                        .lineLimit(1).truncationMode(.tail).help(Self.detail(scope))
                        .lightfieldComponentProbe(probe + ".detail")
                }.frame(maxWidth: .infinity, alignment: .leading)
            }.frame(height: 60).contentShape(Rectangle())
        }.buttonStyle(FeatureLightfieldRowButtonStyle())
            .accessibilityLabel(Self.title(scope))
            .accessibilityValue(selected ? L10n.text("已选", "Selected") : L10n.text("未选", "Not selected"))
            .accessibilityHint(Self.detail(scope))
            .overlay(alignment: .bottom) { FeatureLightfieldHairline() }
            .lightfieldComponentProbe(probe)
    }
}
